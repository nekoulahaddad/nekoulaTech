import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const workspace = fileURLToPath(new URL("../", import.meta.url));

try {
  await build({
    absWorkingDir: workspace,
    entryPoints: ["assets/js/site-effects.js"],
    outfile: "assets/js/site-effects.bundle.js",
    bundle: true,
    format: "iife",
    target: "es2020",
    minify: true,
    legalComments: "none",
    banner: { js: "/* Generated by npm run build. Edit assets/js source modules. */" },
  });
} catch {
  console.error("Site effects could not be built. Check the source diagnostics above.");
  process.exitCode = 1;
}
